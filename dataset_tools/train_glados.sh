#!/usr/bin/env bash
# Fine-tune the GLaDOS VITS voice with Piper, in WSL.
#
# Run dataset_tools/setup_wsl.sh first, then build the corpus with
#   python -m dataset_tools fetch  && python -m dataset_tools build --max-seconds 20
# and copy data/dataset to $DATA_DIR on the WSL ext4 filesystem (NOT /mnt/c -
# the 9p bridge is far too slow for a training dataloader).
#
# Three things here are non-obvious and each one cost a failed run:
#
# 1. --model.warmstart_ckpt, NOT --ckpt_path. `--ckpt_path` resumes a training
#    run: it restores optimizer state, epoch counter and hyperparameters. The
#    published checkpoints were saved by an older Piper whose model took a
#    `sample_bytes` hyperparameter that current Piper rejects, so --ckpt_path
#    dies with "Subcommand 'fit' does not accept option 'model.sample_bytes'".
#    warmstart copies weights only, which is what fine-tuning wants anyway.
#
# 2. train_glados.py, NOT `python -m piper.train`. PyTorch 2.6 flipped
#    torch.load's `weights_only` default to True, and the published checkpoints
#    pickle a pathlib.PosixPath, so loading raises UnpicklingError. The wrapper
#    allowlists the path types before handing off to Piper's CLI.
#
# 3. batch_size 16, not 24. Batch 24 hits CUDA OOM on a 16 GB card with 20s
#    clips, and gradient accumulation is NOT an escape hatch: VITS is a GAN
#    using manual optimization, which Lightning refuses to auto-accumulate.
#    Measured on an RTX 4080 with the 1546-clip corpus:
#      batch 12  60 s/epoch  ~11.0 GB
#      batch 16  40 s/epoch  ~13.3 GB   <- 1.5x faster, ~3 GB headroom left
#      batch 24  OOM
#    16 is the last size with enough margin for the variable-length batches;
#    at 20 the longest clips would run the card out mid-run. Raising it helped
#    because the GPU was only ~50% utilised at 12, not because it was idle on
#    memory.
#
# 4. val_mos needs torchaudio, and its absence is silent. Piper registers a
#    second checkpoint monitoring UTMOS perceptual quality. UTMOS imports
#    torchaudio, which is NOT part of piper's '.[train]' extra; when it is
#    missing the predictor logs "val_mos logging disabled" once and scores
#    nothing, and Lightning then raises MisconfigurationException at every
#    validation epoch and kills the run. We removed the callback and trained
#    ~160 epochs with no perceptual metric at all before noticing.
#
#    setup_wsl.sh now installs torchaudio, and train_glados.py probes the
#    predictor and only drops the callback if it genuinely cannot score. This
#    matters because val_mel does NOT track quality here: it and train_mel
#    drifted up together (so not overfitting) while loss_d nearly doubled - the
#    generator trading mel L1 for adversarial realism. val_mos is the metric
#    that sees what mel L1 cannot.
#
# 5. ljspeech, NOT lessac. Piper's docs use lessac as the example, but the
#    Blizzard 2013 Lessac corpus is licensed for research only and forbids both
#    commercial voice products and redistribution. Fine-tuned weights carry the
#    base weights, so that would follow into any published image. LJSpeech is
#    public domain, also female, and equally good as a base.
set -euo pipefail

PIPER_DIR="${PIPER_DIR:-$HOME/piper1-gpl}"
DATA_DIR="${DATA_DIR:-$HOME/glados_data}"
OUT_DIR="${OUT_DIR:-$HOME/glados_train}"
BATCH_SIZE="${BATCH_SIZE:-16}"
NUM_WORKERS="${NUM_WORKERS:-8}"
MAX_EPOCHS="${MAX_EPOCHS:-1000}"
# 1 pools every source into one voice. >1 trains a speaker embedding per
# recording era, which keeps Portal 2's emotional range from being averaged
# against Portal 1's deliberately flat delivery and Dota 2's announcer mode.
# Must match the number of distinct IDs in metadata.csv, which the dataset
# builder writes with --multi-speaker.
NUM_SPEAKERS="${NUM_SPEAKERS:-1}"
# Set to a checkpoint path to continue an interrupted run in place.
RESUME_CKPT="${RESUME_CKPT:-}"

CKPT_URL="https://huggingface.co/datasets/rhasspy/piper-checkpoints/resolve/main/en/en_US/ljspeech/medium/lj-med_1000.ckpt"
CKPT="$DATA_DIR/ljspeech-medium.ckpt"

if [ ! -f "$CKPT" ]; then
  echo "Downloading public-domain LJSpeech medium checkpoint (846 MB)"
  curl -sSL -o "$CKPT" "$CKPT_URL"
fi

# See note 2 above. Regenerated on every run, NOT written only when absent:
# the old `if [ ! -f ]` guard meant edits here never reached a box that had
# already trained once, and the deployed wrapper silently drifted from this
# script.
cat > "$DATA_DIR/train_glados.py" <<'PY'
"""Launch Piper training with the fixes the published setup needs.

GENERATED by dataset_tools/train_glados.sh on every run. Edit that, not this.
"""

import logging
import math
import pathlib

import librosa
import numpy as np
import torch
import torch.serialization

torch.serialization.add_safe_globals(
    [pathlib.PosixPath, pathlib.WindowsPath, pathlib.PurePosixPath, pathlib.PurePath]
)

from lightning.pytorch.callbacks import ModelCheckpoint  # noqa: E402
from piper.train import __main__ as piper_main  # noqa: E402
from piper.train.vits.lightning import VitsModel  # noqa: E402
from piper.train.vits.mos import MosPredictor  # noqa: E402

_LOGGER = logging.getLogger("train_glados")

# Fixed seed for the validation synthesis. Any constant works; it only has to
# be the same on every epoch and across resumes.
_VAL_SEED = 20250830


# ---------------------------------------------------------------------------
# Perceptual quality: keep the val_mos checkpoint only if UTMOS really loads.
# ---------------------------------------------------------------------------
# Piper's own comment says a missing predictor is harmless - "this callback
# simply finds nothing to save (Lightning warns once and skips)". That is not
# true for this Lightning version: monitoring a metric that is never logged
# raises MisconfigurationException at the end of every validation epoch and
# kills the run. So probe the predictor for real rather than trusting it.
#
# score() swallows every failure and returns None, which is exactly the signal
# wanted here: a missing torchaudio, no network for the torch.hub download and
# a broken checkpoint all come back the same way.
def _mos_works() -> bool:
    return MosPredictor("utmos").score(torch.zeros(22050), 22050) is not None


if _mos_works():
    _LOGGER.info("UTMOS loaded; val_mos will be logged and checkpointed")
else:
    _LOGGER.warning(
        "UTMOS unavailable - dropping the val_mos checkpoint so training can "
        "run. Perceptual quality will NOT be tracked; see setup_wsl.sh."
    )
    # Mutated in place: main() may already hold a reference to this list.
    piper_main._DEFAULT_CALLBACKS[:] = [
        cb
        for cb in piper_main._DEFAULT_CALLBACKS
        if getattr(cb, "monitor", None) != "val_mos"
    ]


# ---------------------------------------------------------------------------
# Make val_mos comparable from epoch to epoch.
# ---------------------------------------------------------------------------
# VITS sampling is stochastic - the stochastic duration predictor and the flow
# both draw noise - and only a handful of held-out utterances are scored. Left
# unseeded, re-scoring the SAME weights twice moves val_mos by more than a real
# epoch of training does, so the curve is noise and cannot answer "is quality
# still improving". Seeding identically each epoch makes every difference a
# model difference.
#
# The RNG state is saved and restored around it. Validation must not consume
# entropy from the training stream, or a resumed run would diverge from an
# uninterrupted one.
_orig_validation_epoch_end = VitsModel.on_validation_epoch_end


def _validation_epoch_end(self):
    cpu_state = torch.random.get_rng_state()
    cuda_states = torch.cuda.get_rng_state_all() if torch.cuda.is_available() else None
    torch.manual_seed(_VAL_SEED)
    try:
        result = _orig_validation_epoch_end(self)
        if not self.trainer.sanity_checking:
            # Inside the seeded window: MCD must measure the same draw each
            # epoch or it inherits the sampling noise it exists to avoid.
            torch.manual_seed(_VAL_SEED)
            _log_mcd(self)
    finally:
        torch.random.set_rng_state(cpu_state)
        if cuda_states is not None:
            torch.cuda.set_rng_state_all(cuda_states)
    if not self.trainer.sanity_checking:
        _log_reference_mos(self)
    return result


# ---------------------------------------------------------------------------
# A ceiling to read val_mos against.
# ---------------------------------------------------------------------------
# UTMOS is not calibrated to this corpus. The GLaDOS recordings THEMSELVES
# score about 3.4, not 5 - they are lossy game assets, and several are filtered
# or spoken over PA effects. So a model at 2.9 is near its ceiling, not
# mediocre, and without the reference the absolute number invites the wrong
# conclusion. Scored once from the same held-out clips the model is judged on,
# then logged every epoch so it draws a flat line beside val_mos.
_REFERENCE = {}


def _log_reference_mos(self) -> None:
    if "value" not in _REFERENCE:
        predictor = MosPredictor("utmos")
        scores = []
        for utt in self.trainer.datamodule.test_dataset:
            score = predictor.score(utt.audio_norm, self.hparams.sample_rate)
            if score is not None:
                scores.append(score)
        _REFERENCE["value"] = (sum(scores) / len(scores)) if scores else None
        if _REFERENCE["value"] is not None:
            _LOGGER.info(
                "Ground-truth UTMOS over %d held-out clips: %.3f",
                len(scores),
                _REFERENCE["value"],
            )
    if _REFERENCE["value"] is not None:
        self.log("val_mos_ref", _REFERENCE["value"], sync_dist=True)


VitsModel.on_validation_epoch_end = _validation_epoch_end


# ---------------------------------------------------------------------------
# val_mcd: distance from GLaDOS's actual recording of the same sentence.
# ---------------------------------------------------------------------------
# The metric that actually answers "is this converging on GLaDOS".
#
# val_mos (UTMOS) predicts how HUMAN a clip sounds, and GLaDOS is deliberately
# not human - the real recordings only score ~3.1 themselves. Maximising it
# would pull the voice toward generic natural speech and away from the target.
# val_mel is an L1 on the teacher-forced reconstruction, so it never sees what
# free-running inference actually produces.
#
# Mel-cepstral distortion compares the model's own synthesis against the
# ground-truth recording of the SAME line, in cepstral space, so it measures
# similarity to this speaker and is indifferent to how robotic she is. Lower is
# better. DTW alignment is required because the stochastic duration predictor
# makes the synthesis a different length than the reference.
# Only sqrt(2), not the usual 10/ln(10)*sqrt(2): power_to_db below is
# 10*log10, so the coefficients already carry that factor and applying it again
# double-counts (it inflated the metric by ~4.3x on the first attempt).
_MCD_K = math.sqrt(2.0)
# Bounds the dynamic range so near-silent frames cannot dominate the distance.
_MCD_TOP_DB = 40.0


def _mcep(y: "np.ndarray", sample_rate: int) -> "np.ndarray":
    """Mel-cepstral coefficients, silence-trimmed and range-limited."""
    trimmed, _ = librosa.effects.trim(y, top_db=30)
    if trimmed.size >= 512:
        y = trimmed
    mel = librosa.feature.melspectrogram(y=y, sr=sample_rate, n_mels=80)
    spec_db = librosa.power_to_db(mel, ref=np.max, top_db=_MCD_TOP_DB)
    # c0 is overall energy, which normalisation already controls; dropping it
    # is the convention and keeps the metric about spectral shape.
    return librosa.feature.mfcc(S=spec_db, n_mfcc=25)[1:]


def _mcd(synth: "np.ndarray", ref: "np.ndarray", sample_rate: int) -> float:
    """Cepstral distance between two waveforms, DTW-aligned.

    NOT calibrated to published MCD. Textbook MCD is single-digit dB; this
    reads ~24 on a converged model, because it is computed from mel-filterbank
    cepstra rather than a WORLD spectral envelope. Measured over 250 epochs it
    moved 27.5 -> 24.5 and ranked checkpoints consistently, so it is a sound
    RELATIVE tracker - just do not compare the number to a paper.

    DTW is required, not optional: the stochastic duration predictor makes each
    synthesis a different length from the reference, so a frame-to-frame
    comparison would mostly measure that misalignment.
    """
    a, b = _mcep(synth, sample_rate), _mcep(ref, sample_rate)
    _, path = librosa.sequence.dtw(X=a, Y=b, metric="euclidean")
    diff = a[:, path[:, 0]] - b[:, path[:, 1]]
    return float(_MCD_K * np.mean(np.sqrt(np.sum(diff * diff, axis=0))))


def _log_mcd(self) -> None:
    scores = []
    for utt in self.trainer.datamodule.test_dataset:
        text = utt.phoneme_ids.unsqueeze(0).to(self.device)
        lengths = torch.LongTensor([len(utt.phoneme_ids)]).to(self.device)
        sid = utt.speaker_id.to(self.device) if utt.speaker_id is not None else None
        with torch.inference_mode():
            audio = self(text, lengths, [0.667, 1.0, 0.8], sid=sid).detach()
        synth = audio.flatten().float().cpu().numpy()
        ref = utt.audio_norm.flatten().float().cpu().numpy()
        if synth.size < 512 or ref.size < 512:
            continue
        scores.append(_mcd(synth, ref, self.hparams.sample_rate))
    if scores:
        self.log("val_mcd", sum(scores) / len(scores), prog_bar=True, sync_dist=True)


# ---------------------------------------------------------------------------
# An audition ladder that does not depend on any metric being right.
# ---------------------------------------------------------------------------
# val_mel is only a proxy in a GAN: the discriminator trades mel L1 for
# perceptual realism, so the best-sounding checkpoint is often not the
# lowest-val_mel one. Measured on this corpus, val_mel and train_mel drifted UP
# together - so not overfitting - while loss_d nearly doubled: the generator
# was paying mel error to win the adversarial game. Keeping only
# top-5-by-val_mel plus last.ckpt can leave a long gap with nothing to listen
# to, so keep an unconditional ladder as well.
# ---------------------------------------------------------------------------
# Checkpoint budget.
# ---------------------------------------------------------------------------
# Each checkpoint is ~845 MB, and three metrics each keeping their own top-5
# plus a periodic ladder filled a 1 TB disk and took WSL down with it. Depth is
# now set by how much each metric is actually trusted: val_mcd is the selector,
# val_mel is a sanity check, val_mos is a diagnostic that only needs its best.
# Sized for a 1000-epoch run: 2+1+1+last plus one periodic per 100 epochs is
# about 13 GB, against ~90 GB at the original settings.
for _cb in piper_main._DEFAULT_CALLBACKS:
    if getattr(_cb, "monitor", None) == "val_mel":
        _cb.save_top_k = 1
    elif getattr(_cb, "monitor", None) == "val_mos":
        _cb.save_top_k = 1

# Best-by-similarity-to-GLaDOS. This is the ladder to pick a release from.
piper_main._DEFAULT_CALLBACKS.append(
    ModelCheckpoint(
        monitor="val_mcd",
        mode="min",
        save_top_k=2,
        save_last=False,
        filename="epoch={epoch}-val_mcd={val_mcd:.3f}",
        auto_insert_metric_name=False,
    )
)

piper_main._DEFAULT_CALLBACKS.append(
    ModelCheckpoint(
        every_n_epochs=100,
        save_top_k=-1,
        save_last=False,
        filename="periodic-epoch={epoch}-val_mel={val_mel:.4f}-val_dur={val_dur:.4f}",
        auto_insert_metric_name=False,
    )
)

piper_main.main()
PY

# Reduces fragmentation; mel length varies per batch.
export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True

cd "$PIPER_DIR"
# shellcheck disable=SC1091
. .venv/bin/activate
cd "$DATA_DIR"

# --ckpt_path restores optimizer state and the epoch counter; warmstart copies
# weights only. Note 1 above explains why --ckpt_path cannot be used with the
# PUBLISHED base checkpoint - it works fine for our own, which current Piper
# wrote, so an interrupted run can be continued without losing progress.
if [ -n "$RESUME_CKPT" ]; then
  echo "Resuming from $RESUME_CKPT"
  set -- --ckpt_path "$RESUME_CKPT"
else
  set -- --model.warmstart_ckpt "$CKPT"
fi

exec python3 train_glados.py fit \
  --data.voice_name glados \
  --data.csv_path "$DATA_DIR/metadata.csv" \
  --data.audio_dir "$DATA_DIR/wavs" \
  --model.sample_rate 22050 \
  --model.num_speakers "$NUM_SPEAKERS" \
  --data.espeak_voice en-us \
  --data.cache_dir "$DATA_DIR/cache" \
  --data.config_path "$DATA_DIR/config.json" \
  --data.batch_size "$BATCH_SIZE" \
  --data.num_workers "$NUM_WORKERS" \
  --trainer.default_root_dir "$OUT_DIR" \
  --trainer.max_epochs "$MAX_EPOCHS" \
  "$@"
